# name: row_number
SELECT id, grp, ROW_NUMBER() OVER (PARTITION BY grp ORDER BY id) FROM facts WHERE id <= 200 ORDER BY id;

# name: rank_nulls
SELECT id, RANK() OVER (ORDER BY grp), DENSE_RANK() OVER (ORDER BY grp DESC) FROM facts WHERE id <= 200 ORDER BY id;

# name: rank_strings
SELECT id, RANK() OVER (ORDER BY cat) FROM facts WHERE id <= 200 ORDER BY id;

# name: running_sum
SELECT id, SUM(qty) OVER (PARTITION BY grp ORDER BY id ROWS BETWEEN 2 PRECEDING AND CURRENT ROW) FROM facts WHERE id <= 200 ORDER BY id;

# name: lag_lead
SELECT id, LAG(qty) OVER (ORDER BY id), LEAD(qty, 2, 0) OVER (ORDER BY id) FROM facts WHERE id <= 200 ORDER BY id;

# name: first_last_value
SELECT id, FIRST_VALUE(qty) OVER (PARTITION BY grp ORDER BY id), LAST_VALUE(qty) OVER (PARTITION BY grp ORDER BY id ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING) FROM facts WHERE id <= 200 ORDER BY id;

# name: distribution
SELECT id, NTILE(4) OVER (ORDER BY id), PERCENT_RANK() OVER (ORDER BY qty, id), CUME_DIST() OVER (ORDER BY qty, id) FROM facts WHERE id <= 200 ORDER BY id;

# name: partition_aggregate
SELECT id, AVG(price) OVER (PARTITION BY cat), COUNT(*) OVER () FROM facts WHERE id <= 200 ORDER BY id;

# name: explicit_null_placement
SELECT id, ROW_NUMBER() OVER (ORDER BY qty NULLS FIRST, id) FROM facts WHERE id <= 200 ORDER BY id;

# name: partition_by_expressions
SELECT id, SUM(qty) OVER (PARTITION BY grp % 3, flag ORDER BY id), COUNT(*) OVER (PARTITION BY UPPER(cat), qty > 500), MAX(id) OVER (PARTITION BY 1) FROM facts WHERE id <= 200 ORDER BY id;

# name: partition_transform
SELECT position, value FROM (SELECT EXPLODE(v_int_arr) OVER (PARTITION BEST) FROM scalars) AS t ORDER BY position, value;

# name: partition_transform_nodes
SELECT position, value FROM (SELECT EXPLODE(v_int_arr) OVER (PARTITION NODES) FROM scalars) AS t ORDER BY position, value;

# name: partition_row
SELECT id, EXPLODE(v_int_arr) OVER (PARTITION ROW) FROM scalars ORDER BY id, position;

# name: partition_left_join
SELECT id, EXPLODE(v_int_arr) OVER (PARTITION LEFT JOIN) FROM scalars ORDER BY id, position;

# name: order_directions_nulls
SELECT id, ROW_NUMBER() OVER (ORDER BY qty ASC NULLS LAST, id), ROW_NUMBER() OVER (ORDER BY qty DESC NULLS FIRST, id), ROW_NUMBER() OVER (ORDER BY qty DESC NULLS LAST, id DESC), ROW_NUMBER() OVER (ORDER BY cat DESC, id), ROW_NUMBER() OVER (ORDER BY flag, qty DESC, id) FROM facts WHERE id <= 200 ORDER BY id;

# name: order_nulls_auto
SELECT id, RANK() OVER (ORDER BY qty NULLS AUTO), RANK() OVER (PARTITION BY grp ORDER BY qty DESC NULLS AUTO, id ASC NULLS AUTO) FROM facts WHERE id <= 200 AND qty IS NOT NULL AND grp IS NOT NULL ORDER BY id;

# name: order_by_expression
SELECT id, RANK() OVER (ORDER BY qty * -1 + 7), DENSE_RANK() OVER (PARTITION BY grp ORDER BY LENGTH(cat) DESC, 1) FROM facts WHERE id <= 200 ORDER BY id;

# name: rows_start_point_only
SELECT id, SUM(qty) OVER (ORDER BY id ROWS UNBOUNDED PRECEDING), SUM(qty) OVER (ORDER BY id ROWS CURRENT ROW), SUM(qty) OVER (PARTITION BY grp ORDER BY id ROWS 3 PRECEDING) FROM facts WHERE id <= 200 ORDER BY id;

# name: rows_between_following
SELECT id, SUM(qty) OVER (ORDER BY id ROWS BETWEEN CURRENT ROW AND 2 FOLLOWING), MIN(qty) OVER (ORDER BY id ROWS BETWEEN 1 FOLLOWING AND 3 FOLLOWING), MAX(qty) OVER (PARTITION BY grp ORDER BY id ROWS BETWEEN 2 PRECEDING AND UNBOUNDED FOLLOWING), COUNT(qty) OVER (ORDER BY id ROWS BETWEEN 1 + 1 PRECEDING AND 4 / 2 FOLLOWING) FROM facts WHERE id <= 200 ORDER BY id;

# name: range_numeric
SELECT id, SUM(qty) OVER (ORDER BY qty RANGE BETWEEN 10 PRECEDING AND 10 FOLLOWING), COUNT(*) OVER (ORDER BY price RANGE 1000.5 PRECEDING), COUNT(*) OVER (PARTITION BY grp ORDER BY qty RANGE UNBOUNDED PRECEDING), COUNT(*) OVER (ORDER BY qty DESC RANGE BETWEEN CURRENT ROW AND UNBOUNDED FOLLOWING), AVG(score) OVER (ORDER BY score RANGE BETWEEN 0.5 PRECEDING AND CURRENT ROW) FROM facts WHERE id <= 200 ORDER BY id;

# name: range_intervals
SELECT id, COUNT(*) OVER (ORDER BY d RANGE BETWEEN INTERVAL '30' DAY PRECEDING AND CURRENT ROW), COUNT(*) OVER (ORDER BY ts RANGE INTERVAL '1' MONTH PRECEDING), COUNT(*) OVER (ORDER BY ts RANGE BETWEEN INTERVAL '2 days' PRECEDING AND INTERVAL '1 12:00' DAY TO MINUTE FOLLOWING), COUNT(*) OVER (ORDER BY d DESC RANGE BETWEEN INTERVAL '1' YEAR PRECEDING AND INTERVAL '6' HOUR FOLLOWING) FROM facts WHERE id <= 200 ORDER BY id;

# name: named_windows
SELECT id, RANK() OVER (w1 ORDER BY qty DESC), RANK() OVER w2, SUM(qty) OVER (w2 ROWS BETWEEN 1 PRECEDING AND CURRENT ROW), COUNT(*) OVER (w1) FROM facts WHERE id <= 200 WINDOW w1 AS (PARTITION BY grp), w2 AS (w1 ORDER BY id) ORDER BY id;

# name: named_window_with_order
SELECT id, SUM(qty) OVER w, LAG(qty) OVER w, AVG(qty) OVER (w RANGE BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING) FROM facts WHERE id <= 200 WINDOW w AS (PARTITION BY grp, cat ORDER BY id) ORDER BY id;
