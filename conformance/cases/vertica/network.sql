# name: inet_aton_ntoa
SELECT id, INET_ATON(ip), INET_NTOA(INET_ATON(ip)), TO_HEX(INET_ATON(ip)), INET_NTOA(n) FROM (SELECT 1 AS id, '209.207.224.40' AS ip, 16909060 AS n UNION ALL SELECT 2, ' 1.2.3.4 ', 4294967295 UNION ALL SELECT 3, 'not an ip', -1 UNION ALL SELECT 4, NULL, NULL UNION ALL SELECT 5, '2001:db8::1', 4294967296) AS t ORDER BY id;

# name: v6_aton_ntoa
SELECT id, TO_HEX(V6_ATON(ip)), V6_NTOA(V6_ATON(ip)), V6_NTOA(HEX_TO_BINARY('20010db8')) FROM (SELECT 1 AS id, '2001:DB8::8:800:200C:417A' AS ip UNION ALL SELECT 2, '1.2.3.4' UNION ALL SELECT 3, '::1.2.3.4' UNION ALL SELECT 4, ' ::1 ' UNION ALL SELECT 5, 'bogus' UNION ALL SELECT 6, NULL) AS t ORDER BY id;

# name: v6_subnets
SELECT id, V6_SUBNETA(V6_ATON(ip), 28), V6_SUBNETA(ip, 64), TO_HEX(V6_SUBNETN(V6_ATON(ip), 28)), V6_SUBNETN(ip, 16), V6_SUBNETA(ip, 129) FROM (SELECT 1 AS id, '2001:db8::8:800:200c:417a' AS ip UNION ALL SELECT 2, 'fe80::1' UNION ALL SELECT 3, '192.168.2.10' UNION ALL SELECT 4, NULL) AS t ORDER BY id;

# name: v6_type
SELECT id, V6_TYPE(V6_ATON(ip)), V6_TYPE(ip) FROM (SELECT 1 AS id, '192.168.2.10' AS ip UNION ALL SELECT 2, '2001:db8::8:800:200c:417a' UNION ALL SELECT 3, '127.0.0.1' UNION ALL SELECT 4, '::' UNION ALL SELECT 5, 'ff02::1' UNION ALL SELECT 6, 'fe80::1' UNION ALL SELECT 7, '0.0.0.0' UNION ALL SELECT 8, '224.0.0.1' UNION ALL SELECT 9, 'bad' UNION ALL SELECT 10, NULL) AS t ORDER BY id;

# name: uri_percent_encoding
SELECT id, URI_PERCENT_ENCODE(v_text), URI_PERCENT_DECODE(URI_PERCENT_ENCODE(v_text)), URI_PERCENT_ENCODE('http://example.com/?=11/15'), URI_PERCENT_DECODE('http://www.faqs.org/rfcs/rfc3986.html+x%20x%6a%a%') FROM scalars ORDER BY id;

# name: uuid_generate
SELECT id, LENGTH(CAST(UUID_GENERATE() AS VARCHAR)), UUID_GENERATE() IS NOT NULL, UUID_GENERATE() <> UUID_GENERATE() FROM scalars ORDER BY id;

