# name: argmax_argmin
SELECT id, ARGMAX(id, cat) OVER (PARTITION BY grp), ARGMIN(id, price) OVER (), ARGMAX(qty, id) OVER (PARTITION BY grp ORDER BY id), ARGMIN(qty, id) OVER (PARTITION BY cat ORDER BY id DESC) FROM facts WHERE id <= 300 ORDER BY id;

# name: avg_sum_analytic
SELECT id, AVG(price) OVER (PARTITION BY grp), AVG(qty) OVER (PARTITION BY grp ORDER BY id), SUM(price) OVER (PARTITION BY cat ORDER BY id ROWS BETWEEN 3 PRECEDING AND 1 FOLLOWING), SUM(qty) OVER () FROM facts WHERE id <= 300 ORDER BY id;

# name: bool_analytic
SELECT id, BOOL_AND(flag) OVER (PARTITION BY grp), BOOL_OR(flag) OVER (PARTITION BY cat ORDER BY id), BOOL_XOR(flag) OVER (PARTITION BY grp ORDER BY id), BOOL_XOR(qty > 500) OVER (PARTITION BY cat), BOOL_AND(qty > 0) OVER (PARTITION BY grp ORDER BY id ROWS 2 PRECEDING), BOOL_OR(flag) OVER (ORDER BY id ROWS BETWEEN 1 PRECEDING AND 1 FOLLOWING) FROM facts WHERE id <= 300 ORDER BY id;

# name: conditional_events
SELECT id, CONDITIONAL_CHANGE_EVENT(cat) OVER (PARTITION BY grp ORDER BY id), CONDITIONAL_CHANGE_EVENT(flag) OVER (ORDER BY id), CONDITIONAL_TRUE_EVENT(qty > 500) OVER (ORDER BY id), CONDITIONAL_TRUE_EVENT(flag) OVER (PARTITION BY cat ORDER BY id) FROM facts WHERE id <= 300 ORDER BY id;

# name: count_analytic
SELECT id, COUNT(qty) OVER (PARTITION BY grp), COUNT(*) OVER (PARTITION BY grp ORDER BY qty), COUNT(1) OVER (ORDER BY id ROWS 3 PRECEDING), COUNT(cat) OVER (PARTITION BY flag ORDER BY id RANGE BETWEEN 5 PRECEDING AND 5 FOLLOWING) FROM facts WHERE id <= 300 ORDER BY id;

# name: min_max_analytic
SELECT id, MIN(qty) OVER (PARTITION BY grp), MAX(cat) OVER (PARTITION BY grp ORDER BY id), MIN(d) OVER (ORDER BY id ROWS BETWEEN CURRENT ROW AND 2 FOLLOWING), MAX(ts) OVER (ORDER BY id ROWS BETWEEN 1 FOLLOWING AND UNBOUNDED FOLLOWING) FROM facts WHERE id <= 300 ORDER BY id;

# name: ranking
SELECT id, RANK() OVER (PARTITION BY grp ORDER BY qty DESC), DENSE_RANK() OVER (PARTITION BY grp ORDER BY cat), ROW_NUMBER() OVER (PARTITION BY cat ORDER BY price DESC NULLS LAST, id), ROW_NUMBER() OVER (ORDER BY qty NULLS FIRST, id DESC) FROM facts WHERE id <= 300 ORDER BY id;

# name: distribution_partitioned
SELECT id, CUME_DIST() OVER (PARTITION BY grp ORDER BY qty), PERCENT_RANK() OVER (PARTITION BY cat ORDER BY price DESC), NTILE(3) OVER (PARTITION BY grp ORDER BY id), NTILE(7) OVER (ORDER BY qty DESC, id) FROM facts WHERE id <= 300 ORDER BY id;

# name: exponential_moving_average
SELECT id, EXPONENTIAL_MOVING_AVERAGE(qty, 0.5) OVER (PARTITION BY grp ORDER BY id), EXPONENTIAL_MOVING_AVERAGE(score, 0.1) OVER (ORDER BY id) FROM facts WHERE id <= 300 ORDER BY id;

# name: first_last_value_ignore_nulls
SELECT id, FIRST_VALUE(qty IGNORE NULLS) OVER (PARTITION BY grp ORDER BY id), LAST_VALUE(cat IGNORE NULLS) OVER (PARTITION BY grp ORDER BY id), FIRST_VALUE(price) OVER (ORDER BY id ROWS BETWEEN 2 FOLLOWING AND 5 FOLLOWING), LAST_VALUE(qty IGNORE NULLS) OVER (PARTITION BY grp ORDER BY id ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING) FROM facts WHERE id <= 300 ORDER BY id;

# name: nth_value
SELECT id, NTH_VALUE(qty, 2) OVER (PARTITION BY grp ORDER BY id), NTH_VALUE(cat, 3 IGNORE NULLS) OVER (PARTITION BY grp ORDER BY id ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING), NTH_VALUE(price, 1) OVER (ORDER BY id ROWS 4 PRECEDING) FROM facts WHERE id <= 300 ORDER BY id;

# name: lag_lead_variants
SELECT id, LAG(qty, 2, -1) OVER (PARTITION BY grp ORDER BY id), LAG(cat) OVER (PARTITION BY grp ORDER BY id), LEAD(cat, 1, 'none') OVER (PARTITION BY grp ORDER BY id), LEAD(d, 3) OVER (ORDER BY id DESC) FROM facts WHERE id <= 300 ORDER BY id;

# name: median_percentiles
SELECT id, MEDIAN(qty) OVER (PARTITION BY grp), MEDIAN(price) OVER (), PERCENTILE_CONT(0.25) WITHIN GROUP (ORDER BY qty DESC) OVER (PARTITION BY grp), PERCENTILE_DISC(0.9) WITHIN GROUP (ORDER BY price ASC) OVER (PARTITION BY cat), PERCENTILE_DISC(0.3) WITHIN GROUP (ORDER BY qty DESC) OVER () FROM facts WHERE id <= 300 ORDER BY id;

# name: stddev_analytic
SELECT id, STDDEV(score) OVER (PARTITION BY grp), STDDEV_POP(qty) OVER (ORDER BY id ROWS 5 PRECEDING), STDDEV_SAMP(price) OVER (PARTITION BY cat ORDER BY id) FROM facts WHERE id <= 300 ORDER BY id;

# name: variance_analytic
SELECT id, VARIANCE(score) OVER (PARTITION BY grp), VAR_POP(qty) OVER (ORDER BY id ROWS BETWEEN 5 PRECEDING AND 5 FOLLOWING), VAR_SAMP(price) OVER (PARTITION BY cat ORDER BY id) FROM facts WHERE id <= 300 ORDER BY id;
